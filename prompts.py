def get_state_value(state: Optional[Dict[str, Any]], *keys: str, default: str) -> str:
    state = state or {}
    for key in keys:
        value = state.get(key)
        if value:
            return str(value)
    return default


def get_expert_system_prompt(expert_mode: str, voice_profile: str = DEFAULT_VOICE_PROFILE, goal: str = DEFAULT_CONTENT_GOAL) -> str:
    expert = EXPERT_MODES.get(expert_mode) or EXPERT_MODES[DEFAULT_EXPERT_MODE]
    voice = VOICE_PROFILES.get(voice_profile) or VOICE_PROFILES[DEFAULT_VOICE_PROFILE]
    goal_data = GOALS.get(goal) or GOALS[DEFAULT_CONTENT_GOAL]

    return "\n\n".join(
        [
            "Ты — AI-ядро контент-системы Naz_AI_Bot.",
            NAZ_CORE_PHILOSOPHY,
            GLOBAL_RULES,
            CONTENT_QUALITY_LAYER,
            ANGLE_ENGINE_LAYER,
            f"EXPERT MODE / что делать:\n{expert['title']} — {expert['short']}\n{expert['system']}",
            f"VOICE PROFILE / как говорить:\n{voice['title']}\nТон: {voice['tone']}\nСтиль: {voice['style']}\n{voice['prompt']}",
            f"CONTENT GOAL / зачем делать:\n{goal_data['title']}\n{goal_data['prompt']}",
        ]
    )


def build_messages(
    *,
    expert_mode: str = DEFAULT_EXPERT_MODE,
    user_text: str,
    memory_context: str = "",
    history: List[Dict[str, str]] | None = None,
    task: str | None = None,
    state: Optional[Dict[str, Any]] = None,
) -> List[Dict[str, str]]:
    """Build messages for OpenRouter/OpenAI-compatible chat completions."""
    expert = get_state_value(state, "expert", "expert_mode", default=expert_mode)
    voice = get_state_value(state, "voice", "voice_profile", default=DEFAULT_VOICE_PROFILE)
    goal = get_state_value(state, "goal", "content_goal", default=DEFAULT_CONTENT_GOAL)

    system_prompt = get_expert_system_prompt(expert, voice, goal)

    if task:
        task_prompt = CONTENT_TASK_PROMPTS.get(task, "")
        if task_prompt:
            system_prompt += f"\n\nТекущая задача:\n{task_prompt}"

    if state:
        recent_topics = state.get("recent_topics") or []
        best_posts = state.get("best_posts") or []
        system_prompt += (
            "\n\nSTATE CONTEXT:\n"
            f"mode: {state.get('mode', 'hybrid')}\n"
            f"role/expert: {expert}\n"
            f"voice: {voice}\n"
            f"goal: {goal}\n"
            f"recent_topics: {recent_topics[-10:]}\n"
            f"content_count: {state.get('content_count', 0)}\n"
            f"quality_profile: {state.get('quality_profile', 'naz_clean_v24')}\n"
            f"content_rules_version: {state.get('content_rules_version', 'v2.4')}\n"
            f"angle_engine: {state.get('angle_engine_version', 'v2.4')}\n"
            f"last_blocked_topic: {state.get('last_blocked_topic', '')}\n"
            f"selected_angle_index: {state.get('selected_angle_index', 0)}\n"
            f"best_posts_preview: {best_posts[-3:]}"
        )

    if memory_context:
        system_prompt += f"\n\nПамять пользователя и системы:\n{memory_context}"

    messages: List[Dict[str, str]] = [{"role": "system", "content": system_prompt}]

    if history:
        for item in history[-10:]:
            role = item.get("role")
            content = item.get("content")
            if role in {"user", "assistant"} and content:
                messages.append({"role": role, "content": content[:4000]})

    messages.append({"role": "user", "content": user_text})
    return messages


def format_roles() -> str:
    lines = ["🧠 Expert modes:", ""]
    for key, data in EXPERT_MODES.items():
        lines.append(f"{key} — {data['title']}: {data['short']}")
    lines.extend(["", "🎭 Voice profiles:", ""])
    for key, data in VOICE_PROFILES.items():
        lines.append(f"{key} — {data['title']}: {data['style']}")
    lines.extend(["", "🎯 Goals:", ""])
    for key, data in GOALS.items():
        lines.append(f"{key} — {data['title']}")
    lines.extend(
        [
            "",
            "Команды:",
            "/role copywriter",
            "/voice tech_hooligan",
            "/goal engagement",
        ]
    )
    return "\n".join(lines)
